    <p>Fellside started in 2011 as a repair bench at the back of a cycle shop in Otley. People brought in leaking jackets and split boots, and kept asking what they should buy next. Now we sell the kit we would buy ourselves, and still fix it when it breaks.</p>

    <h2>How we test</h2>
    <p>Every product spends a season with one of us before it goes on sale. That means wet weekends on the Three Peaks, winter evenings on Ilkley Moor and at least one walk across Kinder in fog. Each product page says where it was tested, with an OS grid reference if you want to go and see for yourself.</p>
    <p>If it leaks, rubs or falls apart, we send it back to the maker and tell them why.</p>

    <h2 id="delivery">Delivery and returns</h2>
